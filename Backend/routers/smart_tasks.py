# ─────────────────────────────────────────────────────────────────────────────
# POST /api/tasks/{task_id}/submit
# User submits their answer/solution — Gemini reviews it and gives feedback
# ─────────────────────────────────────────────────────────────────────────────

@router.post("/{task_id}/submit", response_model=SubmitAnswerResponse)
def submit_task_answer(
    task_id : UUID,
    body    : SubmitAnswerRequest,
    db      : Session = Depends(get_db),
    current_user      = Depends(get_current_user),
):
    """
    User submits their solution/answer to a hard task.
    Gemini reviews it and returns personalised feedback.
    Marks task as completed on submission.
    """
    task = db.query(SmartDailyTask).filter(
        SmartDailyTask.id      == task_id,
        SmartDailyTask.user_id == current_user.id,
    ).first()
    if not task:
        raise HTTPException(status_code=404, detail="Task not found")

    # Build evaluation prompt
    eval_prompt = f"""
You are GrowthOS AI — a concise, encouraging mentor.

TASK: {task.title}
QUESTION: {task.question}
CATEGORY: {task.category}
SKILL: {task.skill_tag}

USER'S ANSWER:
{body.user_answer}

Review their answer in exactly 3 sentences:
1. What they got right (be specific)
2. What they missed or could improve (be constructive)
3. One actionable next step to reinforce this skill

Plain text only. No markdown. Be encouraging but honest.
"""
    profile  = _get_user_profile(current_user.id, db)
    feedback = ask_ai(eval_prompt, profile)

    task.user_answer  = body.user_answer[:3000]
    task.ai_feedback  = feedback
    task.completed    = True
    task.completed_at = datetime.now(timezone.utc)
    db.commit()
    db.refresh(task)

    return SubmitAnswerResponse(
        task_id    = task.id,
        xp_earned  = task.xp_reward,
        ai_feedback= feedback,
        completed  = True,
    )


# ─────────────────────────────────────────────────────────────────────────────
# POST /api/tasks/regenerate
# Manually regenerate today's tasks (user-triggered)
# ─────────────────────────────────────────────────────────────────────────────

@router.post("/regenerate", response_model=List[SmartTaskOut])
def regenerate_today_tasks(
    db          : Session = Depends(get_db),
    current_user          = Depends(get_current_user),
):
    """Delete today's tasks and regenerate fresh ones with Gemini."""
    today = date.today()

    # Delete existing today's tasks
    db.query(SmartDailyTask).filter(
        SmartDailyTask.user_id == current_user.id,
        cast(SmartDailyTask.task_date, Date) == today,
    ).delete(synchronize_session=False)
    db.commit()

    # Generate fresh
    profile    = _get_user_profile(current_user.id, db)
    tasks_data = generate_smart_daily_tasks(profile)

    if not tasks_data:
        raise HTTPException(status_code=500, detail="Task generation failed. Try again.")

    saved = []
    for t in tasks_data:
        task = SmartDailyTask(
            user_id           = current_user.id,
            title             = t.get("title", "Today's Task"),
            question          = t.get("question", ""),
            description       = t.get("description", ""),
            difficulty        = t.get("difficulty", "hard"),
            category          = t.get("category", "Learning"),
            skill_tag         = t.get("skill_tag", ""),
            resource_url      = t.get("resource_url", ""),
            priority          = t.get("priority", "high"),
            estimated_minutes = t.get("estimated_minutes", 45),
            xp_reward         = t.get("xp_reward", 50),
            task_date         = datetime.now(timezone.utc),
        )
        db.add(task)
        saved.append(task)

    db.commit()
    for task in saved:
        db.refresh(task)

    return saved