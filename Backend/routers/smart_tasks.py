# ─────────────────────────────────────────────────────────────────────────────
# GET /api/tasks/today
# Returns today's 3 smart tasks for the current user.
# Auto-generates via Gemini if none exist yet (on-demand fallback).
# ─────────────────────────────────────────────────────────────────────────────

@router.get("/today", response_model=List[SmartTaskOut])
def get_today_smart_tasks(
    db          : Session = Depends(get_db),
    current_user          = Depends(get_current_user),
):
    today = date.today()

    # Check if today's tasks already exist (generated by scheduler or previous call)
    tasks = (
        db.query(SmartDailyTask)
          .filter(
              SmartDailyTask.user_id == current_user.id,
              cast(SmartDailyTask.task_date, Date) == today,
          )
          .order_by(SmartDailyTask.difficulty.desc())   # hard tasks first
          .all()
    )

    if tasks:
        return tasks

    # ── On-demand generation (fallback if scheduler hasn't run yet) ───────────
    profile    = _get_user_profile(current_user.id, db)
    tasks_data = generate_smart_daily_tasks(profile)

    if not tasks_data:
        return []

    saved = []
    for t in tasks_data:
        task = SmartDailyTask(
            user_id           = current_user.id,
            title             = t.get("title", "Today's Task"),
            question          = t.get("question", t.get("description", "")),
            description       = t.get("description", ""),
            difficulty        = t.get("difficulty", "hard"),
            category          = t.get("category", "Learning"),
            skill_tag         = t.get("skill_tag", ""),
            resource_url      = t.get("resource_url", ""),
            priority          = t.get("priority", "high"),
            estimated_minutes = t.get("estimated_minutes", 45),
            xp_reward         = t.get("xp_reward", 50),
            task_date         = datetime.now(timezone.utc),
        )
        db.add(task)
        saved.append(task)

    db.commit()
    for task in saved:
        db.refresh(task)

    return saved


# ─────────────────────────────────────────────────────────────────────────────
# POST /api/tasks/{task_id}/complete
# Marks a task complete (no answer required — just checkbox)
# ─────────────────────────────────────────────────────────────────────────────

@router.post("/{task_id}/complete")
def complete_task(
    task_id     : UUID,
    db          : Session = Depends(get_db),
    current_user          = Depends(get_current_user),
):
    task = db.query(SmartDailyTask).filter(
        SmartDailyTask.id      == task_id,
        SmartDailyTask.user_id == current_user.id,
    ).first()
    if not task:
        raise HTTPException(status_code=404, detail="Task not found")

    task.completed    = True
    task.completed_at = datetime.now(timezone.utc)
    db.commit()
    return {"success": True, "xp_earned": task.xp_reward}


